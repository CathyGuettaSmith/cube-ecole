import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--no-sandbox'])
        errs=[]
        m = await b.new_page(viewport={'width':390,'height':844}, device_scale_factor=2)
        m.on('pageerror', lambda e: errs.append(str(e)))
        m.on('console', lambda x: errs.append('console:'+x.text) if x.type=='error' else None)
        await m.goto('file:///home/claude/rubik/index.html'); await m.wait_for_timeout(500)
        await m.evaluate("document.querySelector('[data-lesson=\"oTC\"]').click()")
        await m.click('#lsGo'); await m.wait_for_timeout(300)
        await m.click('#lsNext'); await m.wait_for_timeout(300)   # OLL 33 (sexy + sledge)
        await m.wait_for_timeout(2500)
        await m.screenshot(path='p_learn.png', full_page=False)
        await m.evaluate("document.getElementById('ovBody').scrollTop = 600")
        await m.wait_for_timeout(200)
        await m.screenshot(path='p_learn2.png')
        await m.click('#lsTabs [data-m="do"]'); await m.wait_for_timeout(400)
        await m.locator('.key').nth(2).click(); await m.wait_for_timeout(1300)
        await m.evaluate("document.getElementById('ovBody').scrollTop = 0")
        await m.screenshot(path='p_bad.png')
        await m.click('[data-p="undo"]'); await m.wait_for_timeout(900)
        for i in range(12):
            if await m.locator('.pracMsg.win').count(): break
            await m.click('[data-p="hint"]'); await m.wait_for_timeout(100)
            await m.locator('.key.hint').first.click(); await m.wait_for_timeout(900)
        await m.wait_for_timeout(400)
        await m.screenshot(path='p_win.png')
        await m.evaluate("document.getElementById('ovBody').scrollTop = 500")
        await m.screenshot(path='p_win2.png')
        await m.click('[data-p="reset"]'); await m.wait_for_timeout(400)
        print('after reset msg:', await m.locator('.pracMsg').inner_text())
        # review
        await m.evaluate("""()=>{const k='rubik-trainer-v2';const s=JSON.parse(localStorage.getItem(k)||'{"srs":{}}');s.srs=s.srs||{};s.srs['oll:45']={b:2,due:0};s.srs['oll:27']={b:1,due:0};localStorage.setItem(k,JSON.stringify(s));}""")
        await m.goto('file:///home/claude/rubik/index.html#reviser'); await m.reload(); await m.wait_for_timeout(500)
        await m.click('#rvGo'); await m.wait_for_timeout(600)
        await m.screenshot(path='p_rev.png')
        await m.click('#rvShow2'); await m.wait_for_timeout(1500)
        await m.screenshot(path='p_rev2.png')
        await m.goto('file:///home/claude/rubik/index.html#bibliotheque'); await m.reload(); await m.wait_for_timeout(500)
        await m.screenshot(path='p_lib.png')
        d = await b.new_page(viewport={'width':1360,'height':1000})
        d.on('pageerror', lambda e: errs.append(str(e)))
        await d.goto('file:///home/claude/rubik/index.html#bibliotheque'); await d.wait_for_timeout(600)
        await d.locator('.card').nth(4).click(); await d.wait_for_timeout(300)
        await d.screenshot(path='p_dlib.png')
        await d.click('#lpTabs [data-m="do"]'); await d.wait_for_timeout(500)
        await d.screenshot(path='p_dlib2.png')
        print(errs)
        await b.close()
asyncio.run(main())
